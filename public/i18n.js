export const locale = () => language === 'lo' ? 'lo-LA' : 'en-US';
export const t = text => language === 'lo' ? (lao[text] || text) : text;
export function initializePreferences(onChange) {
  // Capture static labels once. Dynamic records are translated by the renderers.
  document.querySelectorAll('option:not([value])').forEach(option => option.value = option.textContent);
  const labels = [], walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!['SCRIPT', 'STYLE'].includes(node.parentElement?.tagName) && node.textContent.trim()) labels.push([node, node.textContent]);
  }
  const attributes = [];
  document.querySelectorAll('[placeholder], [aria-label]').forEach(element => {
    for (const name of ['placeholder','aria-label']) if (element.hasAttribute(name)) attributes.push([element,name,element.getAttribute(name)]);
  });
  const apply = () => {
    document.documentElement.lang = language;
    document.title = `TPLUS · ${t('Package monitor')}`;
    for (const [node, original] of labels) if (node.isConnected) node.textContent = original.replace(original.trim(), t(original.trim()));
    for (const [element,name,original] of attributes) element.setAttribute(name,t(original));
    document.getElementById('language').value = language;
  };
  apply();
  document.getElementById('language').addEventListener('change', event => {
    language = event.target.value === 'lo' ? 'lo' : 'en';
    try { localStorage.setItem('tplus-language',language); } catch {}
    apply(); onChange();
  });
  const theme = document.getElementById('theme');
  theme.value = document.documentElement.dataset.theme;
  theme.addEventListener('change', () => {
    document.documentElement.dataset.theme = theme.value;
    try { localStorage.setItem('tplus-theme',theme.value); } catch {}
  });
}
